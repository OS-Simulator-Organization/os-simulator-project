"""Write data/trace_stress.txt: 200 references that shift between working sets.

Uses a fixed linear congruential generator, so the output never depends on the
Python version. Usage: python scripts/make_stress_trace.py
"""
from pathlib import Path

SEED = 301
PAGE_SIZE = 4096
ADDRESS_PAGES = 64
PHASES = (range(0, 4), range(10, 16), range(4, 7), range(30, 38), range(0, 5))
REFERENCES_PER_PHASE = 40
HOT_PERCENT = 80


def lcg(seed):
    state = seed
    while True:
        state = (1103515245 * state + 12345) % 2**31
        yield state >> 8


def stress_addresses(seed=SEED):
    numbers = lcg(seed)
    addresses = []
    for hot_pages in PHASES:
        for _ in range(REFERENCES_PER_PHASE):
            if next(numbers) % 100 < HOT_PERCENT:
                page = hot_pages[next(numbers) % len(hot_pages)]
            else:
                page = next(numbers) % ADDRESS_PAGES
            addresses.append(page * PAGE_SIZE + next(numbers) % PAGE_SIZE)
    return addresses


def main():
    lines = [
        f"# Stress trace: {len(PHASES) * REFERENCES_PER_PHASE} references. Page size {PAGE_SIZE}. Seed {SEED}.",
        "# Generated by scripts/make_stress_trace.py. Do not edit by hand.",
        *(f"0x{address:05X}" for address in stress_addresses()),
    ]
    path = Path(__file__).resolve().parent.parent / "data" / "trace_stress.txt"
    path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
